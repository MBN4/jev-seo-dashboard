"use client";
import Link from "next/link";
import { useMemo, useState } from "react";
import { Download, Eye, FileText, Search } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { PageHeader } from "@/components/common/page-header";
import { SectionCard } from "@/components/common/section-card";
import { EmptyState } from "@/components/common/empty-state";
import { ErrorState } from "@/components/common/error-state";
import { LoadingSkeleton } from "@/components/common/loading-skeleton";
import { FilterChip } from "@/components/common/filter-chip";
import { useApi } from "@/hooks/use-api";
import { api } from "@/lib/api";
import { formatBytes, formatDate } from "@/lib/format";
import { REPORT_LABEL } from "@/lib/report-labels";
import type { ReportFile } from "@/types/api";

type Row = ReportFile & { auditId: string; domain: string; auditDate: string | null };

export default function ReportsCenter() {
  const audits = useApi(() => api.listAudits({ pageSize: 100, status: "completed" }), []);
  const files = useApi<Row[]>(
    audits.data
      ? async () => {
          const withReports = audits.data!.items.filter((a) => a.reports.length);
          const lists = await Promise.all(withReports.map((a) => api.reports(a.id).then((r) => r.items.map((f) => ({ ...f, auditId: a.id, domain: a.domain, auditDate: a.finishedAt })))));
          return lists.flat();
        }
      : null,
    [audits.data],
  );
  const [types, setTypes] = useState<string[]>(["pdf", "xlsx", "md"]);
  const [q, setQ] = useState("");
  const rows = useMemo(() => (files.data ?? []).filter((r) => (!types.length || types.includes(r.type)) && (!q || r.domain.includes(q.toLowerCase()))), [files.data, types, q]);

  return (
    <div className="space-y-6">
      <PageHeader title="Reports" description="Original PDF, Excel, Markdown and JSON files generated by the engine for every audit." />
      <SectionCard bodyClassName="p-0">
        <div className="flex flex-col gap-2 border-b p-4 sm:flex-row sm:items-center sm:justify-between">
          <div className="flex flex-wrap gap-1.5">
            {(["pdf", "xlsx", "md", "json", "digest"] as const).map((t) => (
              <FilterChip key={t} active={types.includes(t)} onClick={() => setTypes((c) => (c.includes(t) ? c.filter((x) => x !== t) : [...c, t]))}>{REPORT_LABEL[t]}</FilterChip>
            ))}
          </div>
          <div className="relative">
            <Search className="pointer-events-none absolute top-1/2 left-2.5 size-3.5 -translate-y-1/2 text-muted-foreground" aria-hidden />
            <Input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Filter by domain" aria-label="Filter by domain" className="h-8 pl-8 sm:w-56" />
          </div>
        </div>
        {audits.error || files.error ? <div className="p-4"><ErrorState error={(audits.error ?? files.error)!} onRetry={audits.reload} /></div>
          : !files.data ? <div className="p-4"><LoadingSkeleton variant="table" /></div>
          : rows.length === 0 ? <EmptyState icon={FileText} title="No reports" description="Completed audits with generated report files appear here." action={<Button asChild><Link href="/audits/new">Start an audit</Link></Button>} />
          : (
            <div className="overflow-x-auto">
              <table className="w-full min-w-[680px] text-sm">
                <thead className="border-b bg-muted/40">
                  <tr>{["Domain", "Audit date", "Report type", "File size", ""].map((h, i) => <th key={i} scope="col" className={`px-3 py-2.5 text-xs font-medium text-muted-foreground ${i >= 3 ? "text-right" : "text-left"}`}>{h || <span className="sr-only">Actions</span>}</th>)}</tr>
                </thead>
                <tbody className="divide-y">
                  {rows.map((r) => (
                    <tr key={r.auditId + r.type} className="hover:bg-muted/40">
                      <td className="px-3 py-2.5"><Link href={`/audits/${encodeURIComponent(r.auditId)}/reports`} className="font-medium hover:underline">{r.domain}</Link></td>
                      <td className="px-3 py-2.5 text-muted-foreground">{formatDate(r.auditDate)}</td>
                      <td className="px-3 py-2.5">{r.label} <span className="font-mono text-xs text-muted-foreground">{r.filename}</span></td>
                      <td className="px-3 py-2.5 text-right tabular">{formatBytes(r.size)}</td>
                      <td className="px-3 py-2.5 text-right">
                        <div className="flex justify-end gap-1">
                          {r.type === "pdf" && <Button variant="ghost" size="icon-sm" asChild><a href={api.reportUrl(r.auditId, "pdf", true)} target="_blank" rel="noreferrer" aria-label={`Preview PDF for ${r.domain}`}><Eye className="size-4" /></a></Button>}
                          <Button variant="outline" size="sm" asChild><a href={api.reportUrl(r.auditId, r.type)} download><Download className="size-3.5" /> Download</a></Button>
                        </div>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
      </SectionCard>
    </div>
  );
}
