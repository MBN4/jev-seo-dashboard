export const TIER_ORDER: Record<Tier, number> = { P0: 0, P1: 1, P2: 2, Weekly: 3, Ignore: 4, Manual: 5 };

/** Tier for a check; unknown checks fall back on severity (critical/high → P1, medium → P2, else Weekly). */
export function priorityOf(id: string, severity?: string): { tier: Tier; owner: Owner } {
  const p = PRIORITIES[id];
  if (p) return p;
  return { tier: severity === "critical" ? "P0" : severity === "high" ? "P1" : severity === "medium" ? "P2" : severity === "info" ? "Ignore" : "Weekly", owner: "SEO" };
}

